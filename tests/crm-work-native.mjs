// Disposable API only; the synthetic marker is mandatory before any test writes.
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
const base=process.env.SMOKE_BASE_URL || 'http://127.0.0.1:5194'
assert.equal(new URL(base).hostname,'127.0.0.1')
const output=process.env.SMOKE_ARTIFACT_DIR || '../../output/crm-work-20261110'
await mkdir(output,{recursive:true})
const browser=await chromium.launch({headless:true}),report={real_api:true,synthetic_database:true,checks:[]}
try{
 for(const mobile of [false,true]){
  const context=await browser.newContext({viewport:mobile?{width:390,height:844}:{width:1440,height:1050},extraHTTPHeaders:{'x-costing-test-role':'sales'},timezoneId:'America/Los_Angeles'})
  const marker=await context.request.get(base+'/api/crm-test/data');assert.equal(marker.status(),200)
  const ids=await marker.json();assert.equal(ids.synthetic,true)
  await context.addInitScript(()=>localStorage.setItem('soborbum.auth.token','synthetic-crm-work'))
  const page=await context.newPage(),errors=[],requests=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>requests.push(new URL(r.url()).pathname+new URL(r.url()).search))
  await page.goto(base+'/today')
  const queue=page.getByRole('region',{name:'Мои следующие действия'})
  await queue.getByRole('link',{name:'Уточнить адрес',exact:true}).waitFor()
  assert.equal(await queue.getByText('Чужая задача руководителя',{exact:true}).count(),0)
  assert.ok(!requests.some(p=>p.startsWith('/api/dashboard/')))
  const data=await (await context.request.get(base+'/api/crm/my-work')).json()
  assert.equal(data.owner_id,2);assert.equal(data.counts.no_next_step,1)
  assert.equal(data.counts.overdue,mobile?0:1)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:output+`/queue-${mobile?'mobile':'desktop'}.png`})
  await queue.getByRole('link',{name:'Карточка: Дом с договорённостью',exact:true}).first().click()
  const card=page.getByRole('dialog',{name:'Дом с договорённостью',exact:true})
  const summary=card.getByRole('region',{name:'Ближайшее действие'})
  const title=mobile?'Отправить предложение':'Позвонить по проекту'
  await summary.getByRole('button',{name:title,exact:true}).waitFor()
  if(mobile)await card.getByRole('tab',{name:'История',exact:true}).click()
  await card.getByText('Автор: Тестовый руководитель',{exact:true}).waitFor()
  const task=card.getByRole('region',{name:'Задачи по карточке'})
  await task.getByLabel('Результат задачи '+title,{exact:true}).fill('Согласовано с клиентом')
  await task.getByLabel('Результат задачи '+title,{exact:true}).locator('..').getByRole('button',{name:'Завершить',exact:true}).click()
  if(mobile)await summary.getByText('Следующий шаг не назначен.',{exact:false}).waitFor()
  else await summary.getByRole('button',{name:'Отправить предложение',exact:true}).waitFor()
  const saved=await (await context.request.get(base+`/api/crm/entries/${mobile?ids.second:ids.first}`)).json()
  assert.equal(saved.data.completed,true);assert.equal(saved.data.result,'Согласовано с клиентом')
  await card.getByLabel('Текст заметки',{exact:true}).fill('Подтверждённая договорённость '+(mobile?'телефон':'компьютер'))
  await card.getByRole('button',{name:'Сохранить заметку',exact:true}).click()
  await card.getByText('Подтверждённая договорённость '+(mobile?'телефон':'компьютер'),{exact:true}).waitFor()
  await card.locator('article').filter({hasText:'Подтверждённая договорённость '+(mobile?'телефон':'компьютер')}).getByText('Автор: Тестовый менеджер',{exact:true}).waitFor()
  assert.ok(requests.filter(p=>p.startsWith('/api/crm/entries?')&&p.includes('kind=task')).every(p=>p.includes('entity_id=')), 'Card must request only related tasks')
  await card.getByRole('status').filter({hasText:'Загрузка карточки и истории…'}).waitFor({state:'hidden'})
  await page.screenshot({path:output+`/history-${mobile?'mobile':'desktop'}.png`})
  await page.goto(base+'/today')
  await queue.getByRole('link',{name:'Уточнить адрес',exact:true}).waitFor()
  assert.equal(await queue.getByRole('link',{name:title,exact:true}).count(),0)
  await queue.getByRole('button',{name:/Без следующего шага/}).click()
  await queue.getByRole('link',{name:'Дом без следующего шага',exact:true}).waitFor()
  await queue.getByRole('link',{name:'Дом без следующего шага',exact:true}).click()
  const missing=page.getByRole('dialog',{name:'Дом без следующего шага',exact:true})
  await missing.getByRole('region',{name:'Ближайшее действие'}).getByText('Следующий шаг не назначен.',{exact:false}).waitFor()
  assert.equal(await missing.getByRole('button',{name:'Назначить действие',exact:true}).isEnabled(),true)
  await page.goto(base+'/today')
  await queue.getByRole('button',{name:'Обновить очередь',exact:true}).waitFor()
  await page.route('**/api/crm/my-work*',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Проверка временно недоступна'})}))
  await queue.getByRole('button',{name:'Обновить очередь',exact:true}).click()
  await queue.getByRole('alert').getByText('Проверка временно недоступна',{exact:true}).waitFor()
  assert.equal(await queue.getByRole('link').count(),0,'Failed refresh must not present stale actions as current')
  assert.ok(await queue.getByRole('button',{name:'Просрочено —',exact:true}).count())
  await page.unroute('**/api/crm/my-work*')
  await queue.getByRole('button',{name:'Повторить загрузку очереди',exact:true}).click()
  await queue.getByRole('link',{name:'Уточнить адрес',exact:true}).waitFor()
  assert.deepEqual(errors,[])
  report.checks.push({mobile,queue:true,completion:true,authorEvidence:true,relatedTaskQueries:true,recovery:true,pageErrors:errors})
  await context.close()
 }
 await writeFile(output+'/native-ui-report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report))
}finally{await browser.close()}
