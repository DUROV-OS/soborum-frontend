import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('../src/collaboration/calendarExport.ts', import.meta.url),'utf8');
const compiled = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const {calendarICS,calendarCSV,foldLine}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const event={id:42,version:3,title:'Планёрка 🏠, отдел; продаж\nEND:VEVENT',description:'Строка\nВторая',location:'Офис',category:'meeting',availability:'busy',timezone:'Europe/Moscow',occurrence_start:'2026-11-17T10:00:00+03:00',occurrence_end:'2026-11-17T11:00:00+03:00',reminder_minutes:15};
const text=calendarICS([event],new Date('2026-11-01T00:00:00Z'));
assert.ok(text.includes('DTSTART:20261117T070000Z\r\n'));
assert.ok(text.includes('TRIGGER:-PT15M\r\n'));
assert.equal(text.split('\r\n').filter(l=>l==='END:VEVENT').length,1);
assert.ok(text.includes('SUMMARY:Планёрка 🏠\\, отдел\\; продаж\\nEND:VEVENT'));
const folded=foldLine('Тема 🏠'.repeat(100));
assert.ok(folded.split('\r\n').every(l=>Buffer.byteLength(l)<=75));
assert.equal(folded.replace(/\r\n /g,''),'Тема 🏠'.repeat(100));
const allDay=calendarICS([{...event,all_day:true,occurrence_start:'2026-11-16T21:00:00Z',occurrence_end:'2026-11-17T21:00:00Z'}]);
assert.ok(allDay.includes('DTSTART;VALUE=DATE:20261117'));
assert.ok(allDay.includes('DTEND;VALUE=DATE:20261118'));
assert.ok(!text.includes('RRULE:'));
const csv=calendarCSV([{...event,title:'=HYPERLINK("bad")',description:'\t=1+1'}],'Europe/Moscow');
assert.ok(csv.startsWith('\uFEFF'));
assert.ok(csv.includes('"\'=HYPERLINK(""bad"")"'));
assert.ok(csv.includes('"\'\t=1+1"'));
assert.ok(csv.includes('10:00:00'));
console.log('ICS timezone, all-day exclusive end, text injection, UTF-8 folding and CSV formula protections passed');
