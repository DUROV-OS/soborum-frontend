// Real API on the isolated synthetic costing server only.
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import { approveItem } from './costing-approval-fixtures.mjs'
const base = process.env.COSTING_TEST_URL ?? 'http://127.0.0.1:5178'
const out = 'test-results/costing-experience'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
const checks = [], errors = []
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true })
  await context.addInitScript(() => { localStorage.setItem('soborbum.auth.token', 'synthetic-costing-only'); for (const id of ['today', 'work', 'admin']) localStorage.setItem('soborbum.onboarding.' + id, '1') })
  const request = context.request
  assert.equal((await request.post(base + '/api/costing-test/reset')).status(), 200)
  async function create(path, data) { const r = await request.post(base + '/api/costing' + path, { data }); assert.ok(r.ok(), await r.text()); return r.json() }
  const a = await create('/materials', { name: 'Доска для теста', unit: 'м3', category: 'Дерево', price: '51', price_source: 'Синтетический прайс', effective_on: '2026-01-01' })
  const b = await create('/materials', { name: 'Другая доска для теста', unit: 'м3', category: 'Дерево', price: '80', price_source: 'Синтетический прайс', effective_on: '2026-01-01' })
  const item = await create('/items', { kind: 'template', title: 'Тестовый дом', content: { category: 'Дом', model: 'Синтетическая комплектация', retail_price: '1000', lines: [{ material_id: a.id, quantity: '2.5', pieces: 2, price: '13.37', price_reason: 'Старая договорная цена' }], expenses: { labor: '0', transport: '0', subcontract: '0', overhead: '0', commercial: '0', advertising: '0', taxes: '0', reserve: '0', evidence: 'Только синтетическая модель' } } })
  const page = await context.newPage()
  await approveItem(request,base,'Тестовый дом')
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(base + '/costing?tab=template')
  let card = page.getByRole('article', { name: 'Типовая смета: Тестовый дом', exact: true })
  await card.getByText('66,85 ₽', { exact: true }).waitFor()
  await page.screenshot({ path: out + '/cards-desktop.png', fullPage: true })
  await card.getByRole('button', { name: 'Состав', exact: true }).click()
  let dialog = page.getByRole('dialog')
  const line = dialog.getByRole('row').filter({ hasText: 'Доска для теста' })
  assert.match(await line.innerText(), /5\s+13,37 ₽\s+66,85 ₽/)
  await dialog.getByLabel('Найти материал в составе').fill('не существует')
  await dialog.getByText('Материалы не найдены', { exact: true }).waitFor()
  await dialog.getByLabel('Найти материал в составе').fill('доска')
  await line.waitFor()
  await dialog.getByLabel('Без цен', { exact: true }).check()
  const downloaded = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Excel состава', exact: true }).click()
  assert.equal(await (await downloaded).failure(), null)
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click()
  checks.push('Карточка и состав показывают серверные суммы, объём × штуки; поиск и выгрузка работают')
  await card.getByRole('button', { name: 'Копия', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Состав изделия: материал 1', { exact: true }).selectOption(String(b.id))
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  card = page.getByRole('article', { name: 'Типовая смета: Тестовый дом — копия', exact: true })
  await card.waitFor()
  await approveItem(request,base,'Тестовый дом — копия')
  await page.reload()
  await card.getByText('400 ₽', { exact: true }).waitFor()
  await card.getByText('Маржа 41.00%', { exact: true }).waitFor()
  const rows = await (await request.get(base + '/api/costing/items?kind=template')).json()
  assert.equal(rows.find(r => r.id === item.id).calculation.materials, '66.85')
  const copy = rows.find(r => r.id !== item.id)
  assert.equal(copy.content.lines[0].price, null)
  assert.equal(copy.content.lines[0].price_reason, '')
  assert.equal(copy.content.lines[0].material_id, b.id)
  assert.equal(copy.calculation.materials, '400.00')
  checks.push('Замена материала в копии сбросила прежнюю ручную цену, сохранила количество и исходник')
  await card.getByRole('button', { name: 'Для клиента', exact: true }).click()
  dialog = page.getByRole('dialog')
  assert.equal(await dialog.getByLabel('Типовая смета', { exact: true }).inputValue(), String(copy.id))
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.getByRole('button', { name: 'Начать обучение', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Знакомство со сметами', exact: true })
  await dialog.getByText('Шаг 1 из 6', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: 'Далее', exact: true }).click()
  await dialog.getByText('Шаг 2 из 6', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: 'Открыть раздел', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.match(page.url(), /tab=template/)
  const nav = page.getByRole('navigation', { name: 'Разделы смет', exact: true })
  await nav.getByRole('button', { name: 'Как работать', exact: true }).click()
  await page.getByLabel('Поиск по руководству').fill('Наценка')
  await page.getByRole('article').getByRole('heading', { name: 'Как считается маржа', exact: true }).waitFor()
  await page.screenshot({ path: out + '/guide-desktop.png', fullPage: true })
  checks.push('Создание предложения из карточки, обучение и поиск по руководству')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(base + '/costing?tab=template')
  await page.getByRole('article', { name: 'Типовая смета: Тестовый дом', exact: true }).waitFor()
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: out + '/cards-mobile.png', fullPage: true })
  const manager = await browser.newContext({ viewport: { width: 390, height: 844 }, extraHTTPHeaders: { 'x-costing-test-role': 'sales' } })
  await manager.addInitScript(() => { localStorage.setItem('soborbum.auth.token', 'synthetic-costing-only') })
  const sales = await manager.newPage()
  const internalReads = []
  sales.on('request', r => { if (/\/api\/costing\/(materials|items|settings|journal)/.test(r.url())) internalReads.push(r.url()) })
  await sales.goto(base + '/costing?tab=help')
  await sales.getByRole('navigation', { name: 'Темы руководства' }).waitFor()
  assert.equal(await sales.getByRole('button', { name: 'Как считается маржа', exact: true }).count(), 0)
  await sales.getByRole('button', { name: 'Начать обучение', exact: true }).click()
  await sales.getByRole('dialog').getByText('Шаг 1 из 2', { exact: true }).waitFor()
  assert.deepEqual(internalReads, [])
  checks.push('Мобильные карточки помещаются в экран; обучение менеджера не запрашивает себестоимость')
  assert.deepEqual(errors, [])
  const report = { checks, pageErrors: errors }
  await writeFile(out + '/result.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally { await browser.close() }
