// Native modules and costing share one disposable database; no external services.
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import { approveItem, approveQuote } from './costing-approval-fixtures.mjs'
const base = process.env.COSTING_TEST_URL ?? 'http://127.0.0.1:5178'
await mkdir('test-results/costing', {recursive:true})
const browser = await chromium.launch({headless:true})
const checks = [], errors = []
try {
  const context = await browser.newContext({viewport:{width:1440,height:1080}})
  await context.addInitScript(() => {localStorage.setItem('soborbum.auth.token','synthetic-costing-only');for(const id of ['today','work','admin'])localStorage.setItem('soborbum.onboarding.'+id,'1')})
  assert.equal((await context.request.post(base+'/api/costing-test/reset')).status(),200)
  const seeded = await context.request.post(base+'/api/costing-test/native')
  assert.equal(seeded.status(),200)
  const ids = await seeded.json()
  const page = await context.newPage()
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/recipes?recipe='+ids.recipe_id)
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Создать типовую смету из техкарты',exact:true}).click()
  await dialog.getByRole('link',{name:'Техкарта связанного дома · типовая смета',exact:true}).click()
  await page.getByRole('link',{name:'Указать модель в настройках комплектации →',exact:true}).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Замороженная цена, ₽',{exact:true}).fill('300')
  await dialog.getByRole('button',{name:'Указать нули для всех расходов',exact:true}).click()
  await dialog.getByLabel('Основание расходов').fill('Синтетическая модель интеграции')
  await dialog.getByRole('button',{name:'Сохранить',exact:true}).click()
  await page.getByRole('dialog').waitFor({state:'hidden'})
  await approveItem(context.request,base,'Техкарта связанного дома')
  checks.push('Общая техкарта открыла типовую смету с теми же материалами и изделием')
  await page.goto(base+'/costing?tab=estimates&deal='+ids.deal_id+'&new=1')
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название / клиент').fill('Дом по связанной сделке')
  await dialog.getByLabel('Типовая смета',{exact:true}).selectOption({label:'Техкарта связанного дома · 300 ₽'})
  await dialog.getByRole('button',{name:'Создать смету',exact:true}).click()
  const signed=await approveQuote(context.request,base,'Дом по связанной сделке')
  await page.goto(base+'/costing?tab=estimates&estimate='+signed.id)
  await page.getByRole('dialog').getByRole('button',{name:'Создать заказ покупателя',exact:true}).click()
  const newOrder = page.getByRole('dialog',{name:'Заказ из утверждённой сметы',exact:true})
  await newOrder.getByLabel('Покупатель',{exact:true}).selectOption(String(ids.buyer_id))
  await newOrder.getByLabel('Организация',{exact:true}).selectOption(String(ids.organization_id))
  await newOrder.getByRole('button',{name:'Создать связанный заказ',exact:true}).click()
  await newOrder.waitFor({state:'hidden'})
  dialog=page.getByRole('dialog')
  await dialog.getByText('Расчёт закреплён',{exact:true}).waitFor()
  assert.equal(await dialog.getByRole('button',{name:'Создать заказ покупателя',exact:true}).count(),0)
  checks.push('Смета сделки создала один обычный заказ с закреплённым расчётом')
  const orderHref=await dialog.getByRole('link',{name:/Заказ №\d+ · строка 1/}).getAttribute('href')
  const quoteHref=await dialog.getByRole('link',{name:/Смета №\d+ · Дом по связанной сделке/}).getAttribute('href')
  await page.goto(base+orderHref)
  dialog=page.getByRole('dialog')
  await dialog.getByText('Расчёт закреплён',{exact:true}).waitFor()
  await dialog.getByRole('button',{name:'Подтвердить заказ',exact:true}).click()
  await dialog.getByText(/^Подтверждён ·/).waitFor()
  await page.goto(base+quoteHref)
  dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Передать норматив в производство',exact:true}).click()
  const norm=dialog.getByRole('link',{name:/Открыть производственный норматив №/})
  await norm.waitFor()
  await norm.click()
  dialog=page.getByRole('dialog')
  await dialog.getByText('Состав закреплён по утверждённой смете заказа.',{exact:false}).waitFor()
  assert.equal(await dialog.getByRole('button',{name:'Изменить норматив',exact:true}).count(),0)
  await dialog.getByRole('button',{name:'Выпустить продукцию',exact:true}).waitFor()
  await page.screenshot({path:'test-results/costing/integrated-production.png',fullPage:true})
  checks.push('Подтверждённый заказ вернулся в смету и открыл закреплённый норматив в штатном производстве')
  assert.deepEqual(errors,[])
  const result={checks,uncaught_page_errors:errors,production_test_writes:false,isolated_database:true}
  await writeFile('test-results/costing/integration.json',JSON.stringify(result,null,2)+'\n')
  console.log(JSON.stringify(result,null,2))
} catch(error) {
  for(const context of browser.contexts()) for(const page of context.pages()) {
    await page.screenshot({path:'test-results/costing/integration-failure.png',fullPage:true})
    console.error('Isolated page:',page.url(),(await page.locator('body').innerText()).slice(-4000))
  }
  throw error
} finally {await browser.close()}
